import { chromium } from 'playwright';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const logs = [];
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text().slice(0, 400)}`));
page.on('pageerror', (e) => logs.push('PAGEERR ' + String(e).slice(0, 400)));
const shot = async (name) => page.screenshot({ path: path.join(root, `docs/design/fog-${name}.png`), timeout: 120000 });
await page.goto('http://127.0.0.1:4173/play/baraki/', { waitUntil: 'domcontentloaded', timeout: 120000 });
await page.waitForTimeout(65000);
await page.mouse.click(1322, 771); await page.waitForTimeout(6000);
await page.mouse.click(800, 651); await page.waitForTimeout(2500);
await page.mouse.click(800, 716); await page.waitForTimeout(9000);
await page.mouse.click(906, 482); await page.waitForTimeout(600);
await page.mouse.click(800, 596); await page.waitForTimeout(6000);
await shot('1-start');
await page.waitForTimeout(12000);
await shot('2-t15');
await page.waitForTimeout(18000);
await shot('3-t33');
await page.waitForTimeout(15000);
await shot('4-t48');
console.log('LOGS:');
for (const l of logs) {
  if (!/FogSimulation|WebGLDemo|SPAWN|error|Capsule|Kernel|Exception/.test(l)) continue;
  console.log(l);
}
await browser.close();
