import { chromium } from 'playwright';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text().slice(0, 160)); });
page.on('pageerror', (e) => errors.push('PAGEERR ' + String(e).slice(0, 160)));
page.on('crash', () => errors.push('PAGE CRASH'));
const t0 = Date.now();
await page.goto('https://lizardan.github.io/gamesup42-pitch/play/baraki/', { waitUntil: 'domcontentloaded', timeout: 120000 });
await page.waitForTimeout(70000);
const canvas = await page.evaluate(() => !!document.querySelector('#unity-canvas'));
console.log('canvas', canvas, 'at', ((Date.now()-t0)/1000).toFixed(0));
await page.mouse.click(1322, 771); await page.waitForTimeout(6000);
await page.mouse.click(800, 651);  await page.waitForTimeout(2500);
await page.mouse.click(800, 716);  await page.waitForTimeout(12000);
await page.screenshot({ path: path.join(root, 'docs/design/soak-start.png'), timeout: 120000 });
console.log('match started at', ((Date.now()-t0)/1000).toFixed(0));
await page.waitForTimeout(600000);
await page.screenshot({ path: path.join(root, 'docs/design/soak-end.png'), timeout: 120000 });
const alive = await page.evaluate(() => !!document.querySelector('#unity-canvas'));
console.log('alive', alive, 'errors', JSON.stringify(errors.slice(0, 8)));
await browser.close();
