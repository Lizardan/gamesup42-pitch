import { chromium } from 'playwright';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const shot = async (n) => { await page.screenshot({ path: path.join(root, `docs/design/${n}.png`), timeout: 120000 }); console.log(n); };
await page.goto('http://127.0.0.1:8099/play/frostspace/', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(48000);
await page.mouse.click(960, 540); await page.waitForTimeout(500);
await page.mouse.click(200, 450);  await page.waitForTimeout(26000);
await page.mouse.click(1340, 820); await page.waitForTimeout(30000);
await page.mouse.click(800, 450); await page.waitForTimeout(700);
await page.mouse.move(800, 450); await page.mouse.move(800, 260, { steps: 10 });
await page.waitForTimeout(1000);
await page.keyboard.down('KeyE'); await page.waitForTimeout(450); await page.keyboard.up('KeyE');
await page.waitForTimeout(1600); await shot('k1');
await page.keyboard.down('KeyF'); await page.waitForTimeout(450); await page.keyboard.up('KeyF');
await page.waitForTimeout(1600); await shot('k2');
await page.keyboard.down('Space'); await page.waitForTimeout(350); await page.keyboard.up('Space');
await page.waitForTimeout(1200); await shot('k3');
await browser.close();
