import { chromium } from 'playwright';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 768, height: 1024 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text().slice(0, 160)); });
page.on('pageerror', (e) => errors.push('PAGEERR ' + String(e).slice(0, 160)));
await page.goto('https://lizardan.github.io/gamesup42-pitch/', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(3000);
await page.evaluate(() => document.getElementById('money').scrollIntoView({ block: 'start' }));
await page.waitForTimeout(1400);
await page.screenshot({ path: path.join(root, 'docs/design/t768-money.png') });
await page.evaluate(() => document.getElementById('play').scrollIntoView({ block: 'start' }));
await page.waitForTimeout(800);
await page.click('button[data-src="assets/video/gameplay.mp4"]');
await page.waitForTimeout(1600);
await page.screenshot({ path: path.join(root, 'docs/design/t768-play.png') });
console.log('console-errors', JSON.stringify(errors.slice(0, 6)));
await browser.close();
