import { chromium } from 'playwright';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e).slice(0, 160)));
await page.goto('http://127.0.0.1:8099/', { waitUntil: 'load' });
await page.locator('#woodStage').scrollIntoViewIfNeeded();
await page.waitForTimeout(1500);
await page.screenshot({ path: path.join(root, 'docs/design/wood-1.png') });
await page.click('.wood-tab[data-place="cathedral"]');
await page.waitForTimeout(1400);
await page.screenshot({ path: path.join(root, 'docs/design/wood-2.png') });
await page.locator('.wood-choice').first().click();
await page.waitForTimeout(900);
await page.screenshot({ path: path.join(root, 'docs/design/wood-3.png') });
console.log('errors', JSON.stringify(errors));
await browser.close();
