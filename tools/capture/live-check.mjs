import { chromium } from 'playwright';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('https://lizardan.github.io/gamesup42-pitch/', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(2500);
await page.evaluate(() => document.getElementById('money').scrollIntoView({ block: 'center' }));
await page.waitForTimeout(3200);
await page.screenshot({ path: path.join(root, 'docs/design/money-live.png') });
await page.evaluate(() => document.getElementById('play').scrollIntoView({ block: 'center' }));
await page.waitForTimeout(800);
await page.click('button[data-src="assets/video/gameplay.mp4"]');
await page.waitForTimeout(1800);
const src = await page.evaluate(() => { const v = document.querySelector('#play video'); return v ? { src: v.currentSrc || v.src, ready: v.readyState, dur: v.duration } : null; });
console.log('video', JSON.stringify(src));
await page.screenshot({ path: path.join(root, 'docs/design/video-live.png') });
console.log('done');
await browser.close();
